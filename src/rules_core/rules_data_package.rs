    /// `(line text, brace depth at line start)` for every line of a Rust file, ignoring braces
    /// inside comments, strings, raw strings and char literals.
    fn lines_with_depth(text: &str) -> Vec<(&str, i32)> {
        let bytes = text.as_bytes();
        let mut depths = vec![0i32];
        let (mut depth, mut i) = (0i32, 0usize);
        while i < bytes.len() {
            match bytes[i] {
                b'\n' => {
                    depths.push(depth);
                    i += 1;
                }
                b'/' if bytes.get(i + 1) == Some(&b'/') => {
                    while i < bytes.len() && bytes[i] != b'\n' {
                        i += 1;
                    }
                }
                b'/' if bytes.get(i + 1) == Some(&b'*') => {
                    i += 2;
                    while i + 1 < bytes.len() && !(bytes[i] == b'*' && bytes[i + 1] == b'/') {
                        if bytes[i] == b'\n' {
                            depths.push(depth);
                        }
                        i += 1;
                    }
                    i += 2;
                }
                b'r' if (bytes.get(i + 1) == Some(&b'"') || bytes.get(i + 1) == Some(&b'#'))
                    && (i == 0 || !(bytes[i - 1].is_ascii_alphanumeric() || bytes[i - 1] == b'_')) =>
                {
                    let mut j = i + 1;
                    let mut hashes = 0;
                    while bytes.get(j) == Some(&b'#') {
                        hashes += 1;
                        j += 1;
                    }
                    if bytes.get(j) != Some(&b'"') {
                        i += 1;
                        continue;
                    }
                    j += 1;
                    loop {
                        if j >= bytes.len() {
                            break;
                        }
                        if bytes[j] == b'\n' {
                            depths.push(depth);
                        }
                        if bytes[j] == b'"' && (0..hashes).all(|k| bytes.get(j + 1 + k) == Some(&b'#')) {
                            j += 1 + hashes;
                            break;
                        }
                        j += 1;
                    }
                    i = j;
                }
                b'"' => {
                    i += 1;
                    while i < bytes.len() && bytes[i] != b'"' {
                        if bytes[i] == b'\\' {
                            i += 1;
                        }
                        if i < bytes.len() && bytes[i] == b'\n' {
                            depths.push(depth);
                        }
                        i += 1;
                    }
                    i += 1;
                }
                b'\'' => {
                    // a char literal ('x', '\n', '\'', '{') -- otherwise a lifetime
                    if bytes.get(i + 1) == Some(&b'\\') {
                        let mut j = i + 2;
                        while j < bytes.len() && bytes[j] != b'\'' {
                            j += 1;
                        }
                        i = j + 1;
                    } else if bytes.get(i + 2) == Some(&b'\'') {
                        i += 3;
                    } else {
                        let ch_len = text[i + 1..].chars().next().map(char::len_utf8).unwrap_or(1);
                        if bytes.get(i + 1 + ch_len) == Some(&b'\'') {
                            i += 2 + ch_len;
                        } else {
                            i += 1;
                        }
                    }
                }
                b'{' => {
                    depth += 1;
                    i += 1;
                }
                b'}' => {
                    depth -= 1;
                    i += 1;
                }
                _ => i += 1,
            }
        }
        text.split('\n').zip(depths).collect()
    }

    /// Every catalog mirror file (`src/rules_core/rules_catalog/`, which holds what the compiled
    /// `rules_tables` module held minus its data) with its module id (`crb/feat_data/general`;
    /// `mod.rs` is its directory). The catalog's own test files are not mirrors.
    fn source_modules() -> Vec<(String, String)> {
        let root = repo_root().join("src/rules_core/rules_catalog");
        let mut out = Vec::new();
        let mut stack = vec![root.clone()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).unwrap().flatten() {
                let path = entry.path();
                if path.is_dir() {
                    stack.push(path);
                } else if path.extension().is_some_and(|e| e == "rs")
                    && !matches!(
                        path.file_name().and_then(|n| n.to_str()),
                        Some("golden_tests.rs" | "control_tests.rs")
                    )
                {
                    let rel = path.strip_prefix(&root).unwrap().to_string_lossy().replace('\\', "/");
                    let module = rel.strip_suffix(".rs").unwrap();
                    let module = module.strip_suffix("/mod").unwrap_or(if module == "mod" { "" } else { module });
                    out.push((module.to_string(), std::fs::read_to_string(&path).unwrap()));
                }
            }
        }
        out.sort();
        out
    }

    fn item_id(module: &str, name: &str) -> String {
        if module.is_empty() { name.to_string() } else { format!("{module}/{name}") }
    }

    /// `pub(crate) static NAME: &[T] = ...` -> `(NAME, "&[T]")` for a file-level line.
    fn const_or_static(line: &str) -> Option<(&str, &str)> {
        let mut rest = line.trim_start();
        for vis in ["pub(crate) ", "pub(super) ", "pub "] {
            if let Some(r) = rest.strip_prefix(vis) {
                rest = r;
                break;
            }
        }
        let rest = rest.strip_prefix("const ").or_else(|| rest.strip_prefix("static "))?;
        let (name, ty) = rest.split_once(':')?;
        let name = name.trim();
        if name.is_empty() || !name.chars().all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_') {
            return None;
        }
        Some((name, ty.split('=').next().unwrap_or("").trim()))
    }

    /// `(` + whitespace + `)` -> `()`, so a zero-argument signature split over lines reads as one.
    fn join_empty_parameter_lists(text: &str) -> String {
        let mut out = String::with_capacity(text.len());
        let mut rest = text;
        while let Some(at) = rest.find('(') {
            out.push_str(&rest[..at]);
            let after = &rest[at + 1..];
            let trimmed = after.trim_start();
            if trimmed.starts_with(')') && trimmed.len() != after.len() {
                out.push_str("()");
                rest = &trimmed[1..];
            } else {
                out.push('(');
                rest = after;
            }
        }
        out.push_str(rest);
        out
    }

    /// `pub fn name() -> Ret {` -> `(name, "Ret")` for a file-level zero-argument function.
    fn zero_arg_fn(line: &str) -> Option<(&str, &str)> {
        let mut rest = line.trim_start();
        for vis in ["pub(crate) ", "pub(super) ", "pub "] {
            if let Some(r) = rest.strip_prefix(vis) {
                rest = r;
                break;
            }
        }
        let rest = rest.strip_prefix("const ").unwrap_or(rest);
        let rest = rest.strip_prefix("fn ")?;
        let (name, rest) = rest.split_once('(')?;
        let rest = rest.trim_start().strip_prefix(')')?;
        let ret = rest.trim_start().strip_prefix("->")?;
        Some((name.trim(), ret.trim().trim_end_matches('{').trim()))
    }

    /// No table data is compiled back in: a file-level `const`/`static` of the catalog is either
    /// a package `Table` (and then a registered id) or not an array at all.
    #[test]
    fn every_file_level_table_is_a_package_table_and_no_array_is_compiled() {
        let ids: BTreeSet<&str> = TABLE_IDS.iter().copied().collect();
        let mut tables = 0;
        let mut missing = Vec::new();
        let mut arrays = Vec::new();
        for (module, text) in source_modules() {
            for (line, depth) in lines_with_depth(&text) {
                if depth != 0 {
                    continue;
                }
                if let Some((name, ty)) = const_or_static(line) {
                    let id = item_id(&module, name);
                    if ty.starts_with('[') || (ty.starts_with('&') && ty.contains('[')) {
                        arrays.push(format!("{id}: {ty}"));
                    } else if ty.contains("rules_catalog::Table<") {
                        tables += 1;
                        if !ids.contains(id.as_str()) {
                            missing.push(id);
                        }
                    }
                }
            }
        }
        assert!(arrays.is_empty(), "file-level arrays compiled into the catalog: {arrays:#?}");
        assert!(missing.is_empty(), "catalog tables with no package file: {missing:#?}");
        assert!(tables >= 222, "scanned {tables} catalog tables");
        println!("catalog tables: {tables}, all registered; compiled arrays: 0");
    }

    #[test]
    fn every_collection_function_is_a_table_or_a_named_view() {
        let ids: BTreeSet<&str> = TABLE_IDS.iter().copied().collect();
        let views: BTreeSet<&str> = VIEWS.iter().map(|(id, _)| *id).collect();
        assert_eq!(views.len(), VIEWS.len(), "a view is listed twice");
        let mut seen = BTreeSet::new();
        let mut unclassified = Vec::new();
        for (module, text) in source_modules() {
            // A signature rustfmt split as `fn name(\n) -> Ret` is one line to the scanner (E4a.1's
            // scanner missed the two `class_skills` functions that way).
            let text = join_empty_parameter_lists(&text);
            // The catalog's builders of the registry tables (`MONSTER_BOOKS`, ...): a function a
            // `Derived::new(..)` static is built by, over package rows.
            let builders: BTreeSet<&str> = text
                .split("Derived::new(")
                .skip(1)
                .filter_map(|rest| rest.split(')').next())
                .map(str::trim)
                .collect();
            for (line, depth) in lines_with_depth(&text) {
                if depth != 0 {
                    continue;
                }
                if let Some((name, ret)) = zero_arg_fn(line)
                    && (ret.contains('[') || ret.starts_with("Vec<") || ret.starts_with("impl Iterator"))
                {
                    let id = item_id(&module, name);
                    if !ids.contains(id.as_str()) && !views.contains(id.as_str()) && !builders.contains(name) {
                        unclassified.push(format!("{id} -> {ret}"));
                    }
                    seen.insert(id);
                }
            }
        }
        assert!(unclassified.is_empty(), "collection functions neither a table nor a named view: {unclassified:#?}");
        let stale: Vec<_> = views.iter().filter(|v| !seen.contains(**v)).collect();
        assert!(stale.is_empty(), "VIEWS names functions the source no longer has: {stale:?}");
        println!("collection functions: {}", seen.len());
    }
