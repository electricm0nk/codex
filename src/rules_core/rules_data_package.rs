#[derive(Serialize)]
struct PackageFileOut<'a, T: Serialize> {
    format: &'static str,
    table: &'a str,
    licence: LicenceStamp,
    rows: &'a [T],
}

/// The package file text for table `id` with `rows` (pretty JSON, trailing newline).
pub fn render_table<T: Serialize>(id: &str, rows: &[T]) -> String {
    let value = serde_json::to_value(rows).unwrap_or_else(|e| panic!("{id}: rows do not serialise: {e}"));
    let file = PackageFileOut { format: FORMAT, table: id, licence: stamp_for(id, &value), rows };
    let mut text = serde_json::to_string_pretty(&file).unwrap_or_else(|e| panic!("{id}: {e}"));
    text.push('\n');
    text
}

/// Every package file `(relative path, text)`, rendered from the compiled tables.
pub fn render_package() -> Vec<(String, String)> {
    render_all().into_iter().map(|(id, text)| (format!("{id}.json"), text)).collect()
}

