/// The registered file-level table whose rows equal `rows` (`""` for an empty slice,
/// [`UNREGISTERED`] when none does). Matched by content, not address: `MONSTER_BOOKS` and
/// `COMPANION_BOOKS` are `const`s, and a reference inside a `const` points at the const's own
/// interned copy of the data, never at the `static` it was written from.
fn static_table_id<T: PartialEq + 'static>(rows: &[T]) -> &'static str {
    if rows.is_empty() {
        return "";
    }
    static_tables_any()
        .into_iter()
        .find(|(_, table)| table.downcast_ref::<&'static [T]>().is_some_and(|candidate| *candidate == rows))
        .map(|(id, _)| id)
        .unwrap_or(UNREGISTERED)
}

