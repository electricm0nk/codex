#[derive(Serialize)]
struct PackageFileOut<'a, T: Serialize> {
    format: &'static str,
    table: &'a str,
    licence: LicenceStamp,
    rows: &'a [T],
}

/// The package file text for table `id` with `rows` (pretty JSON, trailing newline).
pub fn render_table<T: Serialize>(id: &str, rows: &[T]) -> String {
    let value = serde_json::to_value(rows).unwrap_or_else(|e| panic!("{id}: rows do not serialise: {e}"));
    let file = PackageFileOut { format: FORMAT, table: id, licence: stamp_for(id, &value), rows };
    let mut text = serde_json::to_string_pretty(&file).unwrap_or_else(|e| panic!("{id}: {e}"));
    text.push('\n');
    text
}

/// Every package file under `root` as `(relative path, text)`, each loaded as its row type and
/// rendered back in canonical form. The package is the source of the tables (SD-37 E4a.4 removed
/// the compiled module it was first rendered from), so this is a normaliser and a check, not a
/// generator: an edit is made in the JSON, and this re-stamps it.
pub fn render_package(root: &Path) -> Result<Vec<(String, String)>, PackageError> {
    render_all_from(root).into_iter().map(|(id, text)| text.map(|text| (format!("{id}.json"), text))).collect()
}

