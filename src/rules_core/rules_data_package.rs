#[cfg(test)]
fn round_trip_table<T>(id: &'static str, rows: &[T], root: &Path) -> Result<usize, String>
where
    T: Serialize + Deserialize<'static> + 'static,
{
    let expected = render_table(id, rows);
    let path = table_path(root, id);
    let on_disk = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    if on_disk != expected {
        return Err(format!(
            "{}: differs from the compiled table (stale or hand-edited); regenerate with `cargo run --bin rules_tables_package -- --write`",
            path.display()
        ));
    }
    let loaded: &'static [T] = load_table_from(root, id).map_err(|e| e.to_string())?;
    let back = serde_json::to_value(loaded).map_err(|e| e.to_string())?;
    let compiled = serde_json::to_value(rows).map_err(|e| e.to_string())?;
    if back != compiled {
        return Err(format!("{}: the loaded rows differ from the compiled rows", path.display()));
    }
    Ok(loaded.len())
}

#[cfg(test)]
fn rows_schema<T: schemars::JsonSchema>(generator: &mut schemars::r#gen::SchemaGenerator, _rows: &[T]) -> schemars::schema::Schema {
    generator.subschema_for::<Vec<T>>()
}

macro_rules! rules_tables_registry {
    (
        statics { $($sid:literal => $ssrc:path;)* }
        built { $($bid:literal => $bsrc:expr;)* }
    ) => {
        /// Every table the package carries, in registry order: the file-level `const`/`static`
        /// arrays first, then the tables a function builds.
        pub const TABLE_IDS: &[&str] = &[$($sid,)* $($bid,)*];

        fn render_all() -> Vec<(&'static str, String)> {
            vec![$(($sid, render_table($sid, &($ssrc)[..])),)* $(($bid, render_table($bid, &($bsrc)[..])),)*]
        }

        /// Every file-level table as `&dyn Any` (a `&'static [T]` behind it), for
        /// [`static_table_id`]. Only the `statics` section: the registry index rows that call
        /// `static_table_id` are built tables themselves.
        fn static_tables_any() -> Vec<(&'static str, &'static dyn Any)> {
            vec![$(($sid, &$ssrc as &'static dyn Any),)*]
        }

        /// Round-trip every table through its file under `root`: the file equals the rendering
        /// of the compiled table, and the loader's typed rows serialise back to the compiled rows.
        #[cfg(test)]
        pub(crate) fn round_trip_all(root: &Path) -> Vec<(&'static str, Result<usize, String>)> {
            vec![$(($sid, round_trip_table($sid, &($ssrc)[..], root)),)* $(($bid, round_trip_table($bid, &($bsrc)[..], root)),)*]
        }

        #[cfg(test)]
        fn all_rows_schemas(generator: &mut schemars::r#gen::SchemaGenerator) -> Vec<(&'static str, schemars::schema::Schema)> {
            vec![$(($sid, rows_schema(generator, &($ssrc)[..])),)* $(($bid, rows_schema(generator, &($bsrc)[..])),)*]
        }
    };
}

/// `schemas/rules/rules_tables.schema.json`: one package file. `rows` is typed per table through
/// a `oneOf` keyed on the `table` constant; the row types come from their own `schemars` derives
/// (test-only, like E2.2's). Rendered by `sheet_rule::schema_publish_tests` with E2.2's `render`
/// settings.
#[cfg(test)]
pub(crate) fn package_schema() -> Value {
    let mut generator = schemars::r#gen::SchemaSettings::draft07().into_generator();
    let licence = serde_json::to_value(generator.subschema_for::<LicenceStamp>()).expect("schema");
    let variants: Vec<Value> = all_rows_schemas(&mut generator)
        .into_iter()
        .map(|(id, rows)| {
            serde_json::json!({
                "type": "object",
                "required": ["table", "rows"],
                "properties": { "table": { "const": id }, "rows": rows },
            })
        })
        .collect();
    let definitions = serde_json::to_value(generator.definitions()).expect("definitions");
    serde_json::json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "RulesTableFile",
        "description": "One file of the rules_tables data package (data/rules_tables/<table id>.json).",
        "type": "object",
        "required": ["format", "table", "licence", "rows"],
        "additionalProperties": false,
        "properties": {
            "format": { "const": FORMAT },
            "table": { "type": "string", "enum": TABLE_IDS },
            "licence": licence,
            "rows": { "type": "array" },
        },
        "oneOf": variants,
        "definitions": definitions,
    })
}

