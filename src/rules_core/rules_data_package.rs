/// The `format` value every package file carries.
pub const FORMAT: &str = "codex.rules_tables/1";

/// The package directory relative to a repo root (and to the desktop's resource directory, which
/// `tauri.conf.json` lays out the same way).
pub const PACKAGE_RELATIVE: &str = "data/rules_tables";

/// The name of the screen every stamp records.
pub const SCREEN: &str = "pi_screening::classify_field";

/// `repo_root`'s package directory.
pub fn package_root(repo_root: &Path) -> PathBuf {
    repo_root.join(PACKAGE_RELATIVE)
}

/// The package directory this process reads: `CODEX_REPO_ROOT` when set, else the compile-time
/// checkout (`game_system::runtime_repo_root`, the rule the sheet-rule packages already use).
pub fn runtime_package_root() -> PathBuf {
    package_root(&crate::rules_core::game_system::runtime_repo_root())
}

/// The file that carries table `id` under `root`.
pub fn table_path(root: &Path, id: &str) -> PathBuf {
    root.join(format!("{id}.json"))
}

