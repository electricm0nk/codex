//! The `rules_tables` **data package**: format, loader, schema and licence/PI stamp (SD-37 E4a.1,
//! `docs/release/SD-37-starfinder-1e/decisions.md §19`, safe default SD-e).
//!
//! # Format
//!
//! One JSON file per table under `data/rules_tables/`, at `<table id>.json`. A table id is the
//! table's own Rust location with `/` for `::`, e.g. `crb/feat_data/general/GENERAL_TABLE` for
//! `rules_tables::crb::feat_data::general::GENERAL_TABLE`, or `<module>/<fn>` for a table a
//! function builds (`acg/archetype_tables/archetype_swap_tables`). Every file is
//!
//! ```json
//! { "format": "codex.rules_tables/1", "table": "<id>",
//!   "licence": { "license": "OGL", "book": "<first id segment>",
//!                "screen": "pi_screening::classify_field", "pi_hits": [], "redacted": [] },
//!   "rows": [ ...one element per table row, shaped by the row's own serde type... ] }
//! ```
//!
//! The rows are the existing row types (`MonsterStatBlock`, `SpellListEntry`, ...) serialised by
//! their serde derives, so the package says exactly what the compiled table says. The published
//! contract is `schemas/rules/rules_tables.schema.json`, generated by E2.2's generator
//! (`sheet_rule::schema_publish_tests`) from [`package_schema`] and checked by the
//! `rules-schema-check` stage.
//!
//! # Licence / PI stamp
//!
//! Every string value of every row goes through [`pi_screening::classify_field`]. A value that is
//! already the redaction marker (`[redacted PI]`) is listed under `redacted`; any other value the
//! screen flags is a hit, listed under `pi_hits` (`row`, field path, term). The file is stamped
//! `PI` when it has a hit (Product Identity present and NOT redacted: the package ships the
//! compiled table's text unchanged, so a hit the Rust table carries is carried here too, never
//! silently), else `PI-REDACTED` when it has a redacted field, else `OGL` -- the three states of
//! `shape_b_v1::License`. The `pi-sweep` stage (`src/bin/pi_sweep_rules_tables.rs`) re-screens every package file,
//! fails on a stale stamp, and reconciles the hits against `docs/governance/pi-sweep-baseline.tsv`
//! exactly as it does for the Rust tables.
//!
//! # Loader
//!
//! [`load_table_from`] reads one file and returns `&'static [T]` of the table's own row type, so a
//! re-pointed importer (E4a.2) keeps the `&'static` API the compiled tables gave it. Strings are
//! leaked once per load (the package is loaded once per process through [`table`]'s cache), which
//! is the same trade the compiled `&'static str` tables made at build time.
//!
//! # Population
//!
//! [`TABLE_IDS`] is every table of `src/rules_core/rules_tables/`: every file-level `const`/`static`
//! array, every zero-argument function that builds its rows from literals in its own body, the
//! Bestiary 1 stat-block constructors, the class progression tables, the psionic base power-point
//! ladders and the Unchained rogue/summoner feature ladders. The registries over other tables
//! (`MONSTER_BOOKS`, `COMPANION_BOOKS`, `STATIC_CLASS_SPELL_LISTS`) are carried as index rows that
//! name the tables they point at by id. `tests::every_file_level_array_is_a_package_table` and
//! `tests::every_collection_function_is_a_table_or_a_named_view` keep this list closed under new
//! tables.

