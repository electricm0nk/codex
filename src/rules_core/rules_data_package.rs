/// A package file's licence, in `shape_b_v1::License`'s three states: `OGL` when the screen finds
/// nothing, `PI` when a row value carries a Product-Identity term that ships unredacted,
/// `PI-REDACTED` when the only finds are values already replaced by the redaction marker.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
pub enum PackageLicense {
    #[serde(rename = "OGL")]
    Ogl,
    #[serde(rename = "PI")]
    Pi,
    #[serde(rename = "PI-REDACTED")]
    PiRedacted,
}

/// A field whose value is already the redaction marker.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
pub struct RedactedField {
    pub row: usize,
    pub field: String,
}

/// One screen hit: row index, the field path inside the row (`description`, `speeds.0.mode`),
/// and the blacklist term.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
pub struct PiHit {
    pub row: usize,
    pub field: String,
    pub term: String,
}

/// The per-file licence/PI stamp.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
#[serde(deny_unknown_fields)]
pub struct LicenceStamp {
    pub license: PackageLicense,
    /// The rule-book directory the table lives under (the id's first segment).
    pub book: String,
    /// The screen that produced `pi_hits` ([`SCREEN`]).
    pub screen: String,
    pub pi_hits: Vec<PiHit>,
    pub redacted: Vec<RedactedField>,
}

/// Screen every string value of `rows` (a JSON array) with [`pi_screening::classify_field`]:
/// `(unredacted hits, fields already holding the redaction marker)`.
pub fn screen_rows(rows: &Value) -> (Vec<PiHit>, Vec<RedactedField>) {
    let mut hits = Vec::new();
    let mut redacted = Vec::new();
    if let Value::Array(items) = rows {
        for (row, item) in items.iter().enumerate() {
            screen_value(item, row, "", &mut hits, &mut redacted);
        }
    }
    (hits, redacted)
}

fn screen_value(value: &Value, row: usize, path: &str, hits: &mut Vec<PiHit>, redacted: &mut Vec<RedactedField>) {
    let join = |key: &str| if path.is_empty() { key.to_string() } else { format!("{path}.{key}") };
    match value {
        Value::String(text) if text == REDACTED_PI_MARKER => {
            redacted.push(RedactedField { row, field: path.to_string() });
        }
        Value::String(text) => {
            let field = path.rsplit('.').next().unwrap_or(path);
            let (license, _, _, _) = pi_screening::classify_field(field, text);
            if license != License::Ogl {
                let term = pi_screening::PI_BLACKLIST_TERMS
                    .iter()
                    .find(|term| text.contains(*term))
                    .copied()
                    .unwrap_or(text.as_str());
                hits.push(PiHit { row, field: path.to_string(), term: term.to_string() });
            }
        }
        Value::Array(items) => {
            for (i, item) in items.iter().enumerate() {
                screen_value(item, row, &join(&i.to_string()), hits, redacted);
            }
        }
        Value::Object(map) => {
            for (key, item) in map {
                screen_value(item, row, &join(key), hits, redacted);
            }
        }
        Value::Null | Value::Bool(_) | Value::Number(_) => {}
    }
}

/// The stamp a table with these rows carries.
pub fn stamp_for(id: &str, rows: &Value) -> LicenceStamp {
    let (pi_hits, redacted) = screen_rows(rows);
    let license = if !pi_hits.is_empty() {
        PackageLicense::Pi
    } else if !redacted.is_empty() {
        PackageLicense::PiRedacted
    } else {
        PackageLicense::Ogl
    };
    LicenceStamp { license, book: id.split('/').next().unwrap_or(id).to_string(), screen: SCREEN.to_string(), pi_hits, redacted }
}

/// The package's half of the `pi-sweep` gate: re-screen the rows of every `*.json` file under
/// `root`. Returns one [`PiSweepHit`](crate::rules_core::pi_table_sweep::PiSweepHit) per
/// unredacted hit (`file` = `data/rules_tables/<id>.json`, `line` = row index + 1, `context` = the
/// field path), for reconciliation against `docs/governance/pi-sweep-baseline.tsv`, and every file
/// whose stamp disagrees with the re-screen (or that is not a package file at all).
pub fn sweep_package(root: &Path) -> std::io::Result<(Vec<crate::rules_core::pi_table_sweep::PiSweepHit>, Vec<String>)> {
    let mut files = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e == "json") {
                files.push(path);
            }
        }
    }
    files.sort();
    let mut hits = Vec::new();
    let mut bad_stamps = Vec::new();
    for path in files {
        let rel = path.strip_prefix(root).unwrap_or(&path).to_string_lossy().replace('\\', "/");
        let id = rel.strip_suffix(".json").unwrap_or(&rel).to_string();
        let shown = format!("{PACKAGE_RELATIVE}/{rel}");
        match read_envelope(root, &id) {
            Ok((stamp, rows)) => {
                let fresh = stamp_for(&id, &rows);
                if fresh != stamp {
                    bad_stamps.push(format!("{shown}: stamp disagrees with a re-screen of its rows"));
                }
                for hit in fresh.pi_hits {
                    let term = pi_screening::PI_BLACKLIST_TERMS.iter().find(|t| **t == hit.term).copied().unwrap_or("<unknown term>");
                    hits.push(crate::rules_core::pi_table_sweep::PiSweepHit {
                        file: shown.clone(),
                        line: hit.row + 1,
                        term,
                        context: hit.field,
                    });
                }
            }
            Err(e) => bad_stamps.push(e.to_string()),
        }
    }
    Ok((hits, bad_stamps))
}

