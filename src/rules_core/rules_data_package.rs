/// Why a table did not load.
#[derive(Debug)]
pub enum PackageError {
    /// The file could not be read.
    Read { path: PathBuf, error: std::io::Error },
    /// The file is not a package file (bad JSON, wrong `format`, wrong `table`, bad stamp).
    Envelope { path: PathBuf, reason: String },
    /// The rows do not deserialise into the table's row type.
    Rows { path: PathBuf, reason: String },
}

impl fmt::Display for PackageError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            PackageError::Read { path, error } => write!(f, "{}: cannot read: {error}", path.display()),
            PackageError::Envelope { path, reason } => write!(f, "{}: not a rules_tables package file: {reason}", path.display()),
            PackageError::Rows { path, reason } => write!(f, "{}: rows do not match the table's row type: {reason}", path.display()),
        }
    }
}

impl std::error::Error for PackageError {}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PackageFileIn {
    format: String,
    table: String,
    licence: LicenceStamp,
    rows: Value,
}

/// Read and check one package file's envelope; the rows come back as JSON.
pub fn read_envelope(root: &Path, id: &str) -> Result<(LicenceStamp, Value), PackageError> {
    let path = table_path(root, id);
    let text = std::fs::read_to_string(&path).map_err(|error| PackageError::Read { path: path.clone(), error })?;
    let file: PackageFileIn =
        serde_json::from_str(&text).map_err(|e| PackageError::Envelope { path: path.clone(), reason: e.to_string() })?;
    if file.format != FORMAT {
        return Err(PackageError::Envelope { path, reason: format!("format {:?}, expected {FORMAT:?}", file.format) });
    }
    if file.table != id {
        return Err(PackageError::Envelope { path, reason: format!("table {:?}, expected {id:?}", file.table) });
    }
    if !file.rows.is_array() {
        return Err(PackageError::Envelope { path, reason: "rows is not an array".to_string() });
    }
    Ok((file.licence, file.rows))
}

/// Load table `id` from the package under `root` as the table's own row type.
pub fn load_table_from<T>(root: &Path, id: &str) -> Result<&'static [T], PackageError>
where
    T: Deserialize<'static> + 'static,
{
    let (_, rows) = read_envelope(root, id)?;
    let rows = Vec::<T>::deserialize(Leaked(rows))
        .map_err(|e| PackageError::Rows { path: table_path(root, id), reason: e.to_string() })?;
    Ok(Box::leak(rows.into_boxed_slice()))
}

type TableCache = Mutex<HashMap<(&'static str, TypeId), &'static (dyn Any + Send + Sync)>>;

/// Table `id` from [`runtime_package_root`], loaded once per process per row type.
pub fn table<T>(id: &'static str) -> Result<&'static [T], PackageError>
where
    T: Deserialize<'static> + Send + Sync + 'static,
{
    static CACHE: OnceLock<TableCache> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let key = (id, TypeId::of::<T>());
    if let Some(hit) = cache.lock().unwrap_or_else(|p| p.into_inner()).get(&key)
        && let Some(rows) = hit.downcast_ref::<&'static [T]>()
    {
        return Ok(rows);
    }
    let rows: &'static [T] = load_table_from(&runtime_package_root(), id)?;
    let boxed: &'static (dyn Any + Send + Sync) = Box::leak(Box::new(rows));
    cache.lock().unwrap_or_else(|p| p.into_inner()).insert(key, boxed);
    Ok(rows)
}

// ---------------------------------------------------------------------------------------------
// A `Deserializer<'static>` over a JSON value that hands every string out as `&'static str`
// (leaked), so row types with `&'static str` fields load from a file read at run time.
// `serde_json::from_str` can only borrow strings that need no unescaping.
// ---------------------------------------------------------------------------------------------

fn leak_str(text: String) -> &'static str {
    Box::leak(text.into_boxed_str())
}

struct Leaked(Value);

impl<'de> de::Deserializer<'de> for Leaked {
    type Error = serde_json::Error;

    fn deserialize_any<V: Visitor<'de>>(self, visitor: V) -> Result<V::Value, Self::Error> {
        match self.0 {
            Value::Null => visitor.visit_unit(),
            Value::Bool(b) => visitor.visit_bool(b),
            Value::Number(n) => {
                if let Some(u) = n.as_u64() {
                    visitor.visit_u64(u)
                } else if let Some(i) = n.as_i64() {
                    visitor.visit_i64(i)
                } else {
                    visitor.visit_f64(n.as_f64().unwrap_or(f64::NAN))
                }
            }
            Value::String(s) => visitor.visit_borrowed_str(leak_str(s)),
            Value::Array(items) => {
                let len = items.len();
                let mut seq = LeakedSeq(items.into_iter());
                let value = visitor.visit_seq(&mut seq)?;
                if seq.0.len() == 0 {
                    Ok(value)
                } else {
                    Err(de::Error::invalid_length(len, &"fewer elements in the array"))
                }
            }
            Value::Object(map) => visitor.visit_map(LeakedMap { iter: map.into_iter(), value: None }),
        }
    }

    fn deserialize_option<V: Visitor<'de>>(self, visitor: V) -> Result<V::Value, Self::Error> {
        match self.0 {
            Value::Null => visitor.visit_none(),
            other => visitor.visit_some(Leaked(other)),
        }
    }

    fn deserialize_newtype_struct<V: Visitor<'de>>(self, _name: &'static str, visitor: V) -> Result<V::Value, Self::Error> {
        visitor.visit_newtype_struct(self)
    }

    fn deserialize_enum<V: Visitor<'de>>(
        self,
        _name: &'static str,
        _variants: &'static [&'static str],
        visitor: V,
    ) -> Result<V::Value, Self::Error> {
        match self.0 {
            Value::String(s) => {
                visitor.visit_enum(IntoDeserializer::<'de, serde_json::Error>::into_deserializer(leak_str(s)))
            }
            Value::Object(map) if map.len() == 1 => {
                let (variant, value) = map.into_iter().next().expect("one entry");
                visitor.visit_enum(LeakedEnum { variant, value })
            }
            other => Err(de::Error::custom(format!("expected an enum (string or one-key object), found {other}"))),
        }
    }

    serde::forward_to_deserialize_any! {
        bool i8 i16 i32 i64 i128 u8 u16 u32 u64 u128 f32 f64 char str string
        bytes byte_buf unit unit_struct seq tuple tuple_struct map struct identifier ignored_any
    }
}

struct LeakedSeq(std::vec::IntoIter<Value>);

impl<'de> de::SeqAccess<'de> for LeakedSeq {
    type Error = serde_json::Error;
    fn next_element_seed<S: DeserializeSeed<'de>>(&mut self, seed: S) -> Result<Option<S::Value>, Self::Error> {
        match self.0.next() {
            Some(value) => seed.deserialize(Leaked(value)).map(Some),
            None => Ok(None),
        }
    }
    fn size_hint(&self) -> Option<usize> {
        Some(self.0.len())
    }
}

struct LeakedMap {
    iter: serde_json::map::IntoIter,
    value: Option<Value>,
}

impl<'de> de::MapAccess<'de> for LeakedMap {
    type Error = serde_json::Error;
    fn next_key_seed<K: DeserializeSeed<'de>>(&mut self, seed: K) -> Result<Option<K::Value>, Self::Error> {
        match self.iter.next() {
            Some((key, value)) => {
                self.value = Some(value);
                seed.deserialize(Leaked(Value::String(key))).map(Some)
            }
            None => Ok(None),
        }
    }
    fn next_value_seed<S: DeserializeSeed<'de>>(&mut self, seed: S) -> Result<S::Value, Self::Error> {
        match self.value.take() {
            Some(value) => seed.deserialize(Leaked(value)),
            None => Err(de::Error::custom("a map value was requested before its key")),
        }
    }
}

struct LeakedEnum {
    variant: String,
    value: Value,
}

impl<'de> de::EnumAccess<'de> for LeakedEnum {
    type Error = serde_json::Error;
    type Variant = LeakedVariant;
    fn variant_seed<S: DeserializeSeed<'de>>(self, seed: S) -> Result<(S::Value, LeakedVariant), Self::Error> {
        let variant = seed.deserialize(Leaked(Value::String(self.variant)))?;
        Ok((variant, LeakedVariant(self.value)))
    }
}

struct LeakedVariant(Value);

impl<'de> de::VariantAccess<'de> for LeakedVariant {
    type Error = serde_json::Error;
    fn unit_variant(self) -> Result<(), Self::Error> {
        match self.0 {
            Value::Null => Ok(()),
            other => Err(de::Error::custom(format!("unit variant carries a value: {other}"))),
        }
    }
    fn newtype_variant_seed<S: DeserializeSeed<'de>>(self, seed: S) -> Result<S::Value, Self::Error> {
        seed.deserialize(Leaked(self.0))
    }
    fn tuple_variant<V: Visitor<'de>>(self, _len: usize, visitor: V) -> Result<V::Value, Self::Error> {
        de::Deserializer::deserialize_any(Leaked(self.0), visitor)
    }
    fn struct_variant<V: Visitor<'de>>(
        self,
        _fields: &'static [&'static str],
        visitor: V,
    ) -> Result<V::Value, Self::Error> {
        de::Deserializer::deserialize_any(Leaked(self.0), visitor)
    }
}

