    #[test]
    fn every_table_round_trips_through_the_loader() {
        let results = round_trip_all(&checked_in_root());
        let failures: Vec<String> =
            results.iter().filter_map(|(id, r)| r.as_ref().err().map(|e| format!("{id}: {e}"))).collect();
        assert!(failures.is_empty(), "{} of {} tables fail the round trip:\n{}", failures.len(), results.len(), failures.join("\n"));
        assert_eq!(results.len(), TABLE_IDS.len());
        let rows: usize = results.iter().map(|(_, r)| *r.as_ref().unwrap()).sum();
        println!("round trip: {} tables, {rows} rows", results.len());
    }

    #[test]
    fn table_ids_are_unique_and_the_package_holds_exactly_them() {
        let ids: BTreeSet<&str> = TABLE_IDS.iter().copied().collect();
        assert_eq!(ids.len(), TABLE_IDS.len(), "a table id is registered twice");
        let root = checked_in_root();
        let mut on_disk = BTreeSet::new();
        let mut stack = vec![root.clone()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())).flatten() {
                let path = entry.path();
                if path.is_dir() {
                    stack.push(path);
                } else {
                    let rel = path.strip_prefix(&root).unwrap().to_string_lossy().replace('\\', "/");
                    on_disk.insert(rel.strip_suffix(".json").unwrap_or_else(|| panic!("non-JSON file {rel} in the package")).to_string());
                }
            }
        }
        let expected: BTreeSet<String> = ids.iter().map(|s| s.to_string()).collect();
        let stale: Vec<_> = on_disk.difference(&expected).collect();
        let missing: Vec<_> = expected.difference(&on_disk).collect();
        assert!(stale.is_empty() && missing.is_empty(), "stale files {stale:?}; missing files {missing:?}");
    }

    /// The loader hands back the rows as the row type itself, not just equal JSON, and the
    /// catalog reads the same rows (the package is the catalog's only source).
    #[test]
    fn the_loader_returns_the_rows_typed() {
        let root = checked_in_root();
        let feats: &[cat::crb::feats::FeatTableEntry] = load_table_from(&root, "crb/feat_data/general/GENERAL_TABLE").unwrap();
        assert_eq!(feats, &*cat::crb::feat_data::general::GENERAL_TABLE);
        let monsters: &[cat::monster_chassis::MonsterStatBlock] = load_table_from(&root, "bestiary/monster_data/MONSTERS").unwrap();
        assert_eq!(monsters, &*cat::bestiary::monster_data::MONSTERS);
        let b1: &[Beastiary1MonsterRow] = load_table_from(&root, "beastiary1/monster_resolve").unwrap();
        assert_eq!(b1.len(), cat::beastiary1::MonsterId::ALL.len());
        assert!(b1.iter().zip(cat::beastiary1::MonsterId::ALL).all(|(row, id)| row.monster == *id), "one row per MonsterId, in ALL order");
        let cached = table::<cat::crb::feats::FeatTableEntry>("crb/feat_data/general/GENERAL_TABLE").unwrap();
        assert!(std::ptr::eq(cached, table::<cat::crb::feats::FeatTableEntry>("crb/feat_data/general/GENERAL_TABLE").unwrap()));
    }

    /// Planted mutations on a copy of a package file: a Product Identity term written into a row
    /// (the stamp no longer agrees with a fresh screen), a re-indented file and a wrong `table`
    /// each fail. A plain value edit that keeps the file canonical is caught by the golden
    /// digests (`rules_catalog::golden_tests`), not by the round trip.
    #[test]
    fn an_unstamped_pi_row_a_non_canonical_file_or_a_wrong_table_id_is_refused() {
        let id = "crb/feat_data/general/GENERAL_TABLE";
        let row = of_table(&cat::crb::feat_data::general::GENERAL_TABLE);
        let dir = std::env::temp_dir().join(format!("rules-tables-plant-{}", std::process::id()));
        let path = table_path(&dir, id);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        let original = std::fs::read_to_string(table_path(&checked_in_root(), id)).unwrap();
        std::fs::write(&path, &original).unwrap();
        assert!(round_trip_table(row, id, &dir).is_ok(), "the checked-in file round-trips");
        let first_name = original.find("\"name\": \"").expect("a name field");
        let mut planted = original.clone();
        planted.insert_str(first_name + "\"name\": \"".len(), "Asmodeus ");
        std::fs::write(&path, &planted).unwrap();
        assert!(round_trip_table(row, id, &dir).is_err(), "a PI term the stamp does not list passed the round trip");
        std::fs::write(&path, original.replace("\n  ", "\n   ")).unwrap();
        assert!(round_trip_table(row, id, &dir).is_err(), "a re-indented file passed the round trip");
        std::fs::write(&path, original.replace(&format!("\"table\": \"{id}\""), "\"table\": \"crb/other\"")).unwrap();
        assert!(matches!(load_table_from::<cat::crb::feats::FeatTableEntry>(&dir, id), Err(PackageError::Envelope { .. })));
        std::fs::remove_dir_all(&dir).ok();
    }

