/// `deserialize_with` for a `&'static [T]` field: serde has no `Deserialize` for a borrowed
/// slice, so the rows are read into a `Vec` and leaked once.
pub fn leak_slice<'de, D, T>(deserializer: D) -> Result<&'static [T], D::Error>
where
    D: de::Deserializer<'de>,
    T: Deserialize<'de> + 'static,
{
    let rows = Vec::<T>::deserialize(deserializer)?;
    Ok(Box::leak(rows.into_boxed_slice()))
}

/// [`leak_slice`] for an `Option<&'static [T]>` field.
pub fn leak_opt_slice<'de, D, T>(deserializer: D) -> Result<Option<&'static [T]>, D::Error>
where
    D: de::Deserializer<'de>,
    T: Deserialize<'de> + 'static,
{
    let rows = Option::<Vec<T>>::deserialize(deserializer)?;
    Ok(rows.map(|rows| &*Box::leak(rows.into_boxed_slice())))
}

