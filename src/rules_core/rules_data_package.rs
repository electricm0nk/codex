/// A table's row type, carried by value so the registry can name it without spelling its path:
/// [`of_table`] reads it off a catalog `Table`, [`of_vec_fn`]/[`of_slice_fn`] off the catalog
/// function that returns the rows, and the index-row tables name their row struct directly.
pub fn of_table<T>(_table: &cat::Table<T>) -> PhantomData<T> {
    PhantomData
}

/// See [`of_table`].
pub fn of_vec_fn<T>(_rows: fn() -> Vec<T>) -> PhantomData<T> {
    PhantomData
}

/// See [`of_table`].
pub fn of_slice_fn<T>(_rows: fn() -> &'static [T]) -> PhantomData<T> {
    PhantomData
}

/// Table `id` under `root`, loaded as its row type and rendered back to package text.
fn render_from<T>(_row: PhantomData<T>, root: &Path, id: &'static str) -> Result<String, PackageError>
where
    T: Serialize + Deserialize<'static> + Send + Sync + 'static,
{
    let rows: &'static [T] = load_table_from(root, id)?;
    Ok(render_table(id, rows))
}

/// The round trip of one table file under `root`: the file deserialises into its row type, the
/// rows serialise back to the file's own `rows` value, and rendering them reproduces the file
/// byte for byte (canonical layout, and a licence/PI stamp that agrees with a fresh screen).
/// Returns the row count.
pub fn round_trip_table<T>(row: PhantomData<T>, id: &'static str, root: &Path) -> Result<usize, String>
where
    T: Serialize + Deserialize<'static> + Send + Sync + 'static,
{
    let path = table_path(root, id);
    let on_disk = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let loaded: &'static [T] = load_table_from(root, id).map_err(|e| e.to_string())?;
    let back = serde_json::to_value(loaded).map_err(|e| e.to_string())?;
    let file: Value = serde_json::from_str(&on_disk).map_err(|e| format!("{}: {e}", path.display()))?;
    if back != file["rows"] {
        return Err(format!("{}: the typed rows do not serialise back to the file's rows", path.display()));
    }
    let rendered = render_from(row, root, id).map_err(|e| e.to_string())?;
    if rendered != on_disk {
        return Err(format!(
            "{}: not in canonical form (layout or licence/PI stamp); normalise with `cargo run --bin rules_tables_package -- --write`",
            path.display()
        ));
    }
    Ok(loaded.len())
}

#[cfg(test)]
fn rows_schema<T: schemars::JsonSchema>(generator: &mut schemars::r#gen::SchemaGenerator, _row: PhantomData<T>) -> schemars::schema::Schema {
    generator.subschema_for::<Vec<T>>()
}

macro_rules! rules_tables_registry {
    (
        statics { $($sid:literal => $srow:expr;)* }
        built { $($bid:literal => $brow:expr;)* }
    ) => {
        /// Every table the package carries, in registry order: the file-level tables first, then
        /// the tables a function returns (and the index rows of the registries).
        pub const TABLE_IDS: &[&str] = &[$($sid,)* $($bid,)*];

        /// Every table under `root`, loaded as its row type and rendered back (`id`, text).
        pub fn render_all_from(root: &Path) -> Vec<(&'static str, Result<String, PackageError>)> {
            vec![$(($sid, render_from($srow, root, $sid)),)* $(($bid, render_from($brow, root, $bid)),)*]
        }

        /// Round-trip every table through its file under `root` ([`round_trip_table`]).
        pub fn round_trip_all(root: &Path) -> Vec<(&'static str, Result<usize, String>)> {
            vec![$(($sid, round_trip_table($srow, $sid, root)),)* $(($bid, round_trip_table($brow, $bid, root)),)*]
        }

        #[cfg(test)]
        fn all_rows_schemas(generator: &mut schemars::r#gen::SchemaGenerator) -> Vec<(&'static str, schemars::schema::Schema)> {
            vec![$(($sid, rows_schema(generator, $srow)),)* $(($bid, rows_schema(generator, $brow)),)*]
        }
    };
}

/// `schemas/rules/rules_tables.schema.json`: one package file. `rows` is typed per table through
/// a `oneOf` keyed on the `table` constant; the row types come from their own `schemars` derives
/// (test-only, like E2.2's). Rendered by `sheet_rule::schema_publish_tests` with E2.2's `render`
/// settings.
#[cfg(test)]
pub(crate) fn package_schema() -> Value {
    let mut generator = schemars::r#gen::SchemaSettings::draft07().into_generator();
    let licence = serde_json::to_value(generator.subschema_for::<LicenceStamp>()).expect("schema");
    let variants: Vec<Value> = all_rows_schemas(&mut generator)
        .into_iter()
        .map(|(id, rows)| {
            serde_json::json!({
                "type": "object",
                "required": ["table", "rows"],
                "properties": { "table": { "const": id }, "rows": rows },
            })
        })
        .collect();
    let definitions = serde_json::to_value(generator.definitions()).expect("definitions");
    serde_json::json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "RulesTableFile",
        "description": "One file of the rules_tables data package (data/rules_tables/<table id>.json).",
        "type": "object",
        "required": ["format", "table", "licence", "rows"],
        "additionalProperties": false,
        "properties": {
            "format": { "const": FORMAT },
            "table": { "type": "string", "enum": TABLE_IDS },
            "licence": licence,
            "rows": { "type": "array" },
        },
        "oneOf": variants,
        "definitions": definitions,
    })
}

