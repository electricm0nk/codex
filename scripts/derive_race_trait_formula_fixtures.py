#!/usr/bin/env python3
"""Derive `race_trait_formula_entries` for `derived-evaluator-fixtures.json` FROM
THE PINNED PCGEN ORACLE -- never from `data/corpus/`, never from this repo's
Rust tables, and never by importing or running any part of
`src/rules_core/pilot_compute/formula_interpreter.rs`.

WHY (the same constraint every sibling `derive_*_fixtures.py` in this
directory states for its own family, `derive_companion_skill_bonus_fixtures.py`
in particular): a fixture generated by the thing it tests proves nothing.
This script reads the UPSTREAM `.lst` bytes directly, extracts the three
`BONUS:VAR|<name>|<formula>` tokens Undine's own alternate-trait rows carry
with its own regex, and computes every expected value with a small,
from-scratch Python function PER FORMULA SHAPE (below) -- a different
implementation in a different language from
`src/rules_core/derived_evaluator_fixture_check.rs`'s
`run_race_trait_formula_bar_check`, so the two sides cannot silently agree on
a shared bug.

`docs/work-inventory.json` is read for IDENTITY AND SELECTION ONLY -- which
`unit_id` a `(book, corpus_key)` pair carries. No magnitude and no
engine-computed value is ever taken from it.

THE TOKENS, AND WHY THEY NEED THIS SEAM
-----------------------------------------
Undine (Advanced Race Guide) has three selectable alternate racial traits
that each replace the racial-default Spell-Like Ability trait with a
once-per-day breath weapon or fascination effect whose Dice/Duration and DC
are real PCGen arithmetic formulas over total character level (`TL`) and one
ability modifier -- SD31-W26-RACETRAIT-001, extending wave 25's flat-override
seam (`explain_rougarou_flat_override_race_trait` and siblings,
`src/rules_core/pilot_compute/mod.rs`) to the FORMULA shape the interpreter
(wave 25b, `formula_interpreter::PcgenFormulaEvaluator`) now reads, per the
operator's 2026-08-21 ruling overturning SD-27 decisions.md §24.1
(`OPERATOR-RULINGS-2026-08-21.md` §20): "every interpreted value must clear
`derived_evaluator_fixture_check` ... An interpreted value with no fixture is
not done."

Re-verified directly against `PCGEN_ORACLE_SHA=7f818006e371188e5717fd18d74d18a420747fc6`
(`scripts/pcgen-oracle-pin.env`) at write time -- `arg_abilities_race.lst`
lines 776 (Acid Breath), 781 (Nereid Fascination), 782 (Ooze Breath):

  BONUS:VAR|Undine_AcidBreath_Times|1
  BONUS:VAR|Undine_AcidBreath_Dice|min(floor((TL+1)/2),5)
  BONUS:VAR|Undine_AcidBreath_DC|10+(TL/2)+CON

  BONUS:VAR|Undine_NereidFascination_Times|1
  BONUS:VAR|Undine_NereidFascination_Duration|max((TL/2),1)
  BONUS:VAR|Undine_NereidFascination_DC|10+(TL/2)+CHA

  BONUS:VAR|Undine_OozeBreath_Times|1
  BONUS:VAR|Undine_OozeBreath_Dice|min(floor((TL+1/2)),5)
  BONUS:VAR|Undine_OozeBreath_DC|10+(TL/2)+CON

(Ooze Breath's Dice formula really is `TL+1/2`, not `(TL+1)/2` -- confirmed
byte-for-byte against the oracle; not a transcription slip on this script's
part. It is upstream PCGen's own long-standing arithmetic, carried faithfully
rather than "corrected" -- for non-negative integer `TL` it collapses to
`min(TL, 5)`, one dice lower on average than Acid Breath's `(TL+1)/2` shape at
even levels, which this script's own independent evaluation reproduces
exactly rather than silently matching Acid Breath's shape.)

TRUNCATION CONVENTION, MATCHED DELIBERATELY
---------------------------------------------
`formula_interpreter.rs`'s own module doc (point 1) documents ITS convention
for a not-yet-built consumer: carry arithmetic in `f64` end-to-end, and
truncate toward zero only ONCE, at the whole expression's own return
boundary -- `floor()`/`min()`/`max()` still apply exactly where written, but
a bare `+`/`/` chain with no explicit `floor()` (e.g. `10+(TL/2)+CON`) is
NOT floored mid-expression. This script mirrors that convention exactly
(`_trunc_toward_zero`, applied once, at the end of each function below) so
this independently-computed expected value is testing the SAME semantic the
engine's evaluator commits to, not a different one.

WHAT IS DELIBERATELY NOT COVERED
---------------------------------
Only these six formulas, all fixed and independently re-derived from the
oracle. `Undine_*_Times|1` is a bare literal (no arithmetic at all) and is
still included in each entry's `expected_at_sample_points` for full corpus
fidelity, but is constant across every sample point by construction.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURE_PATH = REPO_ROOT / "tests" / "fixtures" / "rules_core" / "derived-evaluator-fixtures.json"

def pcgen_data_root() -> Path:
    root = os.environ.get("PCGEN_CORPUS_ROOT")
    if root:
        return Path(root)
    home = os.environ.get("HOME")
    if not home:
        sys.exit("HOME must be set (or PCGEN_CORPUS_ROOT given) to locate the PCGen corpus")
    return Path(home) / "workspace" / "repos" / "pcgen" / "data"


UPSTREAM_LST_RELATIVE = "pathfinder/paizo/roleplaying_game/advanced_race_guide/arg_abilities_race.lst"

# Sample points chosen for mutation sensitivity: TL spans low/mid/high and
# both parities (odd TL exercises the "no mid-expression floor" truncation
# convention above -- 10+(TL/2)+CON differs from 10+floor(TL/2)+CON at odd
# TL). Ability modifiers span negative/zero/positive, independent of TL.
SAMPLE_POINTS = [
    {"TL": 1, "CON": 0, "CHA": 0},
    {"TL": 2, "CON": 2, "CHA": -1},
    {"TL": 4, "CON": -2, "CHA": 3},
    {"TL": 5, "CON": 1, "CHA": 1},
    {"TL": 7, "CON": 5, "CHA": -3},
    {"TL": 10, "CON": -5, "CHA": 10},
    {"TL": 13, "CON": 3, "CHA": 0},
    {"TL": 16, "CON": 0, "CHA": 4},
    {"TL": 19, "CON": -1, "CHA": 2},
    {"TL": 20, "CON": 10, "CHA": -5},
]


def _trunc_toward_zero(x: float) -> int:
    return math.trunc(x)


def undine_acid_breath_dice(tl: int, con: int, cha: int) -> int:
    del cha
    return _trunc_toward_zero(min(math.floor((tl + 1) / 2), 5))


def undine_acid_breath_dc(tl: int, con: int, cha: int) -> int:
    del cha
    return _trunc_toward_zero(10 + (tl / 2) + con)


def undine_ooze_breath_dice(tl: int, con: int, cha: int) -> int:
    del con, cha
    return _trunc_toward_zero(min(math.floor(tl + 1 / 2), 5))


def undine_ooze_breath_dc(tl: int, con: int, cha: int) -> int:
    del cha
    return _trunc_toward_zero(10 + (tl / 2) + con)


def undine_nereid_fascination_duration(tl: int, con: int, cha: int) -> int:
    del con, cha
    return _trunc_toward_zero(max((tl / 2), 1))


def undine_nereid_fascination_dc(tl: int, con: int, cha: int) -> int:
    del con
    return _trunc_toward_zero(10 + (tl / 2) + cha)


# (unit_id, book, record_key, upstream_line, {formula_field: (raw_formula, expected_fn)})
RECORDS = [
    (
        "advanced_race_guide:race_trait:undine_acid_breath",
        "advanced_race_guide",
        "Undine ~ Acid Breath",
        776,
        {
            "Undine_AcidBreath_Times": ("1", lambda tl, con, cha: 1),
            "Undine_AcidBreath_Dice": ("min(floor((TL+1)/2),5)", undine_acid_breath_dice),
            "Undine_AcidBreath_DC": ("10+(TL/2)+CON", undine_acid_breath_dc),
        },
    ),
    (
        "advanced_race_guide:race_trait:undine_nereid_fascination",
        "advanced_race_guide",
        "Undine ~ Nereid Fascination",
        781,
        {
            "Undine_NereidFascination_Times": ("1", lambda tl, con, cha: 1),
            "Undine_NereidFascination_Duration": ("max((TL/2),1)", undine_nereid_fascination_duration),
            "Undine_NereidFascination_DC": ("10+(TL/2)+CHA", undine_nereid_fascination_dc),
        },
    ),
    (
        "advanced_race_guide:race_trait:undine_ooze_breath",
        "advanced_race_guide",
        "Undine ~ Ooze Breath",
        782,
        {
            "Undine_OozeBreath_Times": ("1", lambda tl, con, cha: 1),
            "Undine_OozeBreath_Dice": ("min(floor((TL+1/2)),5)", undine_ooze_breath_dice),
            "Undine_OozeBreath_DC": ("10+(TL/2)+CON", undine_ooze_breath_dc),
        },
    ),
]


def upstream_lst_sha256() -> str:
    path = pcgen_data_root() / UPSTREAM_LST_RELATIVE
    if not path.is_file():
        print(f"error: pinned oracle checkout not found at {path}", file=sys.stderr)
        sys.exit(1)
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_tokens_against_oracle() -> None:
    """Re-reads the pinned .lst bytes and confirms every formula this script
    hard-codes above is byte-present on the exact cited line -- refuses to
    generate a fixture from a formula the oracle does not actually carry."""
    path = pcgen_data_root() / UPSTREAM_LST_RELATIVE
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    for _unit_id, _book, record_key, line_no, formulas in RECORDS:
        line = lines[line_no - 1]
        if f"KEY:{record_key}" not in line:
            print(f"error: {UPSTREAM_LST_RELATIVE}:{line_no} does not carry KEY:{record_key}", file=sys.stderr)
            sys.exit(1)
        for field, (raw_formula, _fn) in formulas.items():
            token = f"BONUS:VAR|{field}|{raw_formula}"
            if token not in line:
                print(f"error: {UPSTREAM_LST_RELATIVE}:{line_no} does not carry {token!r}", file=sys.stderr)
                sys.exit(1)


def load_unit_ids() -> set[str]:
    inventory_path = REPO_ROOT / "docs" / "work-inventory.json"
    doc = json.loads(inventory_path.read_text(encoding="utf-8"))
    return {u["id"] for u in doc["units"]}


def build_entries() -> list[dict]:
    entries = []
    sha256 = upstream_lst_sha256()
    known_ids = load_unit_ids()
    for unit_id, book, record_key, line_no, formulas in RECORDS:
        if unit_id not in known_ids:
            print(f"error: {unit_id} is not in docs/work-inventory.json", file=sys.stderr)
            sys.exit(1)
        raw_formulas = {field: raw for field, (raw, _fn) in formulas.items()}
        samples = []
        for point in SAMPLE_POINTS:
            tl, con, cha = point["TL"], point["CON"], point["CHA"]
            expected = {field: fn(tl, con, cha) for field, (_raw, fn) in formulas.items()}
            samples.append({"TL": tl, "CON": con, "CHA": cha, "expected": expected})
        entries.append(
            {
                "unit_id": unit_id,
                "book": book,
                "record_key": record_key,
                "upstream_lst": UPSTREAM_LST_RELATIVE,
                "upstream_lst_sha256": sha256,
                "upstream_line": line_no,
                "formulas": raw_formulas,
                "expected_at_sample_points": samples,
            }
        )
    return entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()

    verify_tokens_against_oracle()
    entries = build_entries()

    doc = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
    doc["race_trait_formula_token_family"] = (
        "BONUS:VAR|<name>|<formula> (a PF1 racial-alternate-trait magnitude computed from total "
        "character level TL and, for some fields, one ability modifier, e.g. Undine's breath-weapon "
        "Dice/DC and Nereid Fascination's Duration/DC)"
    )
    doc["race_trait_formula_derivation"] = (
        "PCGen `BONUS:VAR|<name>|<formula>` tokens on a race_trait alternate-racial-trait row, "
        "transcribed verbatim from the pinned oracle at write time and re-verified byte-for-byte "
        "by this script's own verify_tokens_against_oracle() before every generation run. "
        "expected_at_sample_points pins each formula's evaluated result at ten (TL, CON, CHA) "
        "points chosen for mutation sensitivity (both TL parities, negative/zero/positive ability "
        "modifiers), computed by a plain per-formula Python function -- NOT read back from this "
        "repo's evaluator."
    )
    doc["race_trait_formula_independence"] = (
        "scripts/derive_race_trait_formula_fixtures.py re-reads the pinned upstream .lst bytes "
        "directly, re-verifies the exact BONUS:VAR token text against the oracle, and computes "
        "every expected value with a small hand-written Python function per formula shape -- "
        "structurally independent of "
        "src/rules_core/derived_evaluator_fixture_check.rs's run_race_trait_formula_bar_check "
        "and of src/rules_core/pilot_compute/formula_interpreter.rs's PcgenFormulaEvaluator, "
        "neither of which this script imports, calls, or reads. It opens no file under "
        "data/corpus/, reads no Rust table. docs/work-inventory.json is read for identity and "
        "selection only (unit_id membership)."
    )
    doc["race_trait_formula_entries"] = entries

    if args.check:
        current = doc.get("race_trait_formula_entries")
        on_disk = json.loads(FIXTURE_PATH.read_text(encoding="utf-8")).get("race_trait_formula_entries")
        if current != on_disk:
            print("error: race_trait_formula_entries would change -- run without --check to update", file=sys.stderr)
            sys.exit(1)
        print(f"OK: {len(entries)} race_trait_formula_entries up to date")
        return

    FIXTURE_PATH.write_text(json.dumps(doc, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} race_trait_formula_entries to {FIXTURE_PATH}")


if __name__ == "__main__":
    main()
