def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="derive and print, write nothing")
    ap.add_argument("--report", action="store_true", help="print the skip census to stderr and exit")
    args = ap.parse_args()

    data_root = pcgen_data_root()
    entries, skipped = derive(data_root)

    if args.report:
        for s in skipped:
            print(f"SKIPPED: {s}", file=sys.stderr)
        print(f"\n{len(entries)} derived, {len(skipped)} skipped", file=sys.stderr)
        return

    for s in skipped:
        print(f"SKIPPED: {s}", file=sys.stderr)

    if args.check:
        print(json.dumps(entries, indent=2))
        print(f"\n{len(entries)} derived, {len(skipped)} skipped", file=sys.stderr)
        return

    doc = json.loads(FIXTURE_PATH.read_text())
    doc["class_feature_description_token_family"] = TOKEN_FAMILY
    doc["class_feature_description_derivation"] = DERIVATION
    doc["class_feature_description_independence"] = INDEPENDENCE
    doc["class_feature_description_entries"] = entries
    FIXTURE_PATH.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {len(entries)} class_feature_description_entries ({len(skipped)} skipped) to {FIXTURE_PATH}")


if __name__ == "__main__":
    main()
