/// **The `derived` bar.** For every held `derived` unit the fixture covers, the
/// engine's evaluator — reached through the shipping `compute_equipment_effects`
/// seam, over the real on-disk corpus, with that item and nothing else equipped
/// — produces exactly the ability list and magnitude the upstream corpus row
/// states.
///
/// The only accepted reason for not checking an entry is that its book has no
/// ingest in this repo at all (`data/corpus/<book>/equipment` absent), which is
/// asserted as a fact about the filesystem rather than taken on trust. A book
/// that IS ingested and whose record does not evaluate correctly fails here;
/// it is not excused, and its units stay `held`.
#[test]
fn engine_evaluator_output_equals_the_corpus_derived_expected_value() {
    // Delegates to `codex::rules_core::derived_evaluator_fixture_check::run_bar_check`
    // -- the exact function `v06_work_inventory` calls to emit the `derived`
    // done-rung evidence, so this test and the generator can never disagree
    // about which units cleared the bar.
    let report = run_bar_check(&repo_root());

    for book in report.engine_does_not_hold.values().collect::<BTreeSet<_>>() {
        assert!(
            !repo_root().join("data").join("corpus").join(book).join("equipment").is_dir(),
            "{book} was skipped as un-ingested, but its equipment corpus exists — the \
             skip is only ever allowed to be a fact about the filesystem"
        );
    }

    let stale_uncleared: Vec<_> = report
        .cleared
        .iter()
        .filter(|id| uncleared_reason(id).is_some())
        .collect();
    assert!(
        stale_uncleared.is_empty(),
        "{} unit(s) clear the `derived` bar but are still on the `UNCLEARED` record — \
         delete these entries: {:?}",
        stale_uncleared.len(),
        stale_uncleared
    );

    assert_uncleared_set_is_exact(&report.failures, "derived bar");
    assert!(
        !report.cleared.is_empty(),
        "no fixture entry reached the evaluator, which would make this bar vacuous"
    );
    eprintln!(
        "derived evaluator-vs-fixture: {} of {} covered units cleared the bar; \
         {} did NOT and stay `held` (see `UNCLEARED`); {} belong to \
         books with no ingest in this repo",
        report.cleared.len(),
        report.fixtures_total,
        report.failures.len(),
        report.engine_does_not_hold.len()
    );
}

/// The reference derivation refuses malformed input instead of guessing.
///
/// Without this, a `BONUS:STAT` field the grammar does not cover could silently
/// produce a plausible number and every other assertion here would compare two
/// fabrications.
#[test]
fn reference_derivation_refuses_what_it_cannot_parse() {
    assert_eq!(
        reference_bonus_stat("BONUS:STAT|STR|2|TYPE=Enhancement"),
        Some((vec!["STR".to_string()], 2))
    );
    assert_eq!(
        reference_bonus_stat("BONUS:STAT|INT,WIS,CHA|4|TYPE=Enhancement"),
        Some((vec!["INT".to_string(), "WIS".to_string(), "CHA".to_string()], 4))
    );
    assert_eq!(reference_bonus_stat("BONUS:STAT|WIS|-2"), Some((vec!["WIS".to_string()], -2)));
    // A different BONUS family, a formula the grammar does not evaluate, a
    // missing magnitude, and a non-BONUS token all refuse rather than guess.
    assert_eq!(reference_bonus_stat("BONUS:WEAPON|DAMAGE|min(STR,0)"), None);
    assert_eq!(reference_bonus_stat("BONUS:STAT|STR|CASTERLEVEL/2"), None);
    assert_eq!(reference_bonus_stat("BONUS:STAT|STR"), None);
    assert_eq!(reference_bonus_stat("COST:4000"), None);
}
