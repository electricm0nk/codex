function makeSemaphore(n) {
  let free = n
  const q = []
  const release = () => { free++; if (q.length) { free--; q.shift()(release) } }
  return { acquire: () => new Promise(res => { if (free > 0) { free--; res(release) } else q.push(res) }) }
}
