"""E4.1: write proposed-names.md, one proposed display name for every placeholder hit E0.3 found.

    python3 -I <this file>          # rewrite proposed-names.md beside it from ../epic_0/placeholder-names.json
    python3 -I <this file> --check  # exit 0 only if the written file equals the recomputation

Input: E0.3's `placeholder-names.json` (the 201 corpus `data.name` hits). Each row cites the record's
book, its `SOURCEPAGE` token, and the record's own description (or the printed table heading where
one was read). Does not cover: the printed page itself was opened only for the APG rods and
giant-hide armor (legacy.aonprd.com, the record's own `description_source.url` site).
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = subprocess.check_output(['git', '-C', HERE, 'rev-parse', '--show-toplevel'], text=True).strip()
SRC = os.path.join(HERE, '..', 'epic_0', 'placeholder-names.json')
OUT = os.path.join(HERE, 'proposed-names.md')
BOOK = {
    'advanced_players_guide': "Advanced Player's Guide", 'core_rulebook': 'Core Rulebook',
    'inner_sea_magic': 'Inner Sea Magic', 'occult_adventures': 'Occult Adventures',
    'pathfinder_unchained': 'Pathfinder Unchained', 'ultimate_combat': 'Ultimate Combat',
    'ultimate_magic': 'Ultimate Magic', 'ultimate_psionics': 'Ultimate Psionics',
}
SPELLING = {'Inflitrator': 'Infiltrator'}  # the LST key's typo; the item's own description is the source


def variant(key):
    """`Psicrown (Beast)` -> `Beast`; `Setting Stone (Power Echo (3rd))` -> `Power Echo (3rd)`."""
    m = re.match(r'^[^(]*\((.*)\)$', key)
    return m.group(1) if m else key


def propose(kind, key, name, desc):
    """(proposed name, basis) for one hit."""
    if kind == 'skill':
        return ('Lore (Deity)', 'the book name holds Product Identity (a deity name, decisions.md §19a); '
                'a codex-neutral name, never the book word')
    if key.startswith('Rod ('):
        spell, grade = variant(key).split('/')
        m = re.match(r'Elemental (\w+)', spell)
        spell = f'Elemental ({m.group(1)})' if m else spell
        tail = '' if grade == 'Normal' else f', {grade}'
        return (f'Metamagic Rod, {spell}{tail}',
                f'APG rods table row "Metamagic, {spell.split(" (")[0].lower()}{tail.lower()}"')
    if 'NAME' in name:
        v = SPELLING.get(variant(key), variant(key))
        out = name.replace('[NAME]', v)
        out = re.sub(r'\bOf\b', 'of', out)
        if 'Giant-hide' in name:
            return out, 'APG heading "Giant-Hide Armor", one per giant: "giant form I (ogre, troll, hill giant, ...)"'
        return out, 'the source name with its variant from the record key'
    if kind == 'ability':
        tag = re.search(r'\[(.*)\]', name).group(1)
        word = '+1 bonus' if tag == '+1' else 'class skill'
        return re.sub(r'\[.*\]', f'({word})', name), f'record text: "{desc[:70]}"'
    return name.replace('[', '(').replace(']', ')'), 'the book writes the sub-type in parentheses'


def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def build():
    hits = [h for h in json.load(open(SRC))['hits'] if h['surface'].startswith('corpus:')]
    rows = []
    for h in sorted(hits, key=lambda h: h['record']):
        rec = json.load(open(os.path.join(ROOT, h['record'])))
        data, kind = rec['data'], h['surface'].split(':', 1)[1]
        page = next((t['value'] for t in data.get('raw_tokens', []) if t.get('key') == 'SOURCEPAGE'), 'no SOURCEPAGE')
        desc = data.get('description') or ''
        proposed, basis = propose(kind, data['key'], data['name'], desc)
        book = BOOK.get(h['book'], h['book'])
        cite = f'{book} {page}; {basis}' + (f'; record: "{desc[:90]}"' if desc and kind != 'ability' else '')
        rows.append(f"| `{h['record']}` | {kind} | {cell(data['key'])} | {cell(data['name'])} | **{cell(proposed)}** | {cell(cite)} |")
    head = [
        '# E4.1 proposed display names (for operator approval at E4.G)',
        '',
        f'Generated by `python3 -I {os.path.relpath(__file__, ROOT)}` from E0.3\'s `placeholder-names.json`.',
        f'{len(rows)} rows: one per corpus record whose `data.name` holds `[`, `]` or `NAME`. Nothing here ships until the',
        'operator approves it (decisions.md §22, 20-a); E4.2 moves the approved names into `src/rules_core/display_name.rs`.',
        'The all-kinds test (`rules_core::display_name::tests::no_display_name_of_any_kind_holds_a_placeholder_the_proposal_does_not_cover`)',
        'reads the first column: it fails on any placeholder name a row here does not cover.',
        '',
        '| Record | Kind | Variant (`data.key`) | Shown today | Proposed | Book text |',
        '|---|---|---|---|---|---|',
    ]
    return '\n'.join(head + rows) + '\n'


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        ok = open(OUT).read() == text
        print('OK' if ok else 'proposed-names.md differs from the recomputation')
        sys.exit(0 if ok else 1)
    open(OUT, 'w').write(text)
    print(OUT, text.count('\n| `data/corpus/'))
