#!/usr/bin/env python3
"""Generate artifacts/cycle_0/sd38-workflow.js from the SD-38 package.
PREFIX = workflow-instruction.md §2.1 fenced block, verbatim. PROCEDURE = §6, verbatim.
Cards (id, tier, cargo, deps, phase, lane) come from kanban.md + epic-breakdown.md §0."""
import re, json, sys, pathlib
PKG = pathlib.Path(__file__).resolve().parents[2]
wi = (PKG / 'workflow-instruction.md').read_text()
kb = (PKG / 'kanban.md').read_text()
eb = (PKG / 'epic-breakdown.md').read_text()

# --- PREFIX: the ```text block under ### 2.1
m = re.search(r'### 2\.1.*?```text\n(.*?)```', wi, re.S)
PREFIX = m.group(1)
# --- PROCEDURE: ## 6. ... up to ## 7.
m = re.search(r'(## 6\. Per-cycle procedure.*?)(?=\n## 7\.)', wi, re.S)
PROCEDURE = m.group(1)

# --- cargo from epic-breakdown §0 table: | id | Parallel? | Tier | Cargo? | Notes |
cargo = {}
in_s0 = False
for line in eb.splitlines():
    if line.startswith('## §0'): in_s0 = True
    elif line.startswith('## Epic C'): in_s0 = False
    if not in_s0 or not re.match(r'^\| (C|E)[0-9]', line): continue
    cols = [c.strip() for c in line.strip().strip('|').split('|')]
    if len(cols) < 5: continue
    cid = cols[0].split()[0]; c = cols[3].lower()
    cargo[cid] = c.startswith('yes')
assert len(cargo) == 68, len(cargo)
# --- cards from kanban
cards = []
for line in kb.splitlines():
    if not re.match(r'^\| (C|E)[0-9]', line): continue
    cols = [c.strip() for c in line.strip().strip('|').split('|')]
    cid, title, tier, status, deps = cols[0], cols[1], cols[2], cols[3], cols[4]
    deps = re.findall(r'(?<![\w.])((?:C|E)\d+(?:\.(?:\d+|V|MC))?)(?![\w.])', deps)
    cards.append(dict(id=cid, title=title, tier=tier, deps=deps, cargo=cargo.get(cid, True)))

def phase_of(cid):
    if cid.startswith('C'): return 'C — package + cut'
    if cid.startswith('E0'): return 'E0 — seam'
    if cid == 'E1.V': return 'E1.V — verify'
    if cid.startswith('E1'): return 'E1 — transcription'
    if cid in ('E2.10', 'E2.MC'): return 'E2 — assembly'
    if cid.startswith('E2'): return 'E2 — engine lanes'
    if cid.startswith('E6'): return 'E6 — catalogs'
    if cid.startswith('E3'): return 'E3 — create'
    if cid.startswith('E4'): return 'E4 — sheet'
    if cid.startswith('E5'): return 'E5 — improve'
    return 'E7 — closure'

def lane_of(cid):
    if re.match(r'^E1\.[1-8]$', cid): return 'e1-' + cid.split('.')[1]
    if cid in ('E2.1','E2.2','E2.3','E2.4'): return 'a'
    if cid in ('E2.5','E2.6','E2.7','E2.8'): return 'b'
    if cid == 'E2.9': return 'c'
    if cid.startswith('E6'): return 'e6'
    if cid.startswith('E3'): return 'e3'
    if cid.startswith('E4'): return 'e4'
    return 'main'

for c in cards:
    c['phase'] = phase_of(c['id']); c['lane'] = lane_of(c['id'])
    if c['id'] == 'C0': c['tier'] = 'lead'

TIERS = {'opus','sonnet','haiku','lead','sonnet + opus'}
bad = [c['id'] for c in cards if c['tier'] not in TIERS]
assert not bad, bad
ids = {c['id'] for c in cards}
for c in cards:
    bad = [d for d in c['deps'] if d not in ids]
    assert not bad, (c['id'], bad)
    assert c['id'] not in c['deps'], c['id']
# every dep cell token that looks like an id must be a real id (a note in the deps cell is a defect)
assert len(cards) == 68, len(cards)

JS = r'''export const meta = {
  name: 'sd38-cyberpunk-red',
  description: 'SD-38 Cyberpunk RED — seam, transcription, engine, create, sheet, improve, catalogs, closure',
  phases: [
    { title: 'C — package + cut' }, { title: 'E0 — seam' }, { title: 'E1 — transcription' },
    { title: 'E1.V — verify' }, { title: 'E2 — engine lanes' }, { title: 'E6 — catalogs' },
    { title: 'E2 — assembly' }, { title: 'E3 — create' }, { title: 'E4 — sheet' },
    { title: 'E5 — improve' }, { title: 'E7 — closure' },
  ],
}
// Generated by gen_sd38_workflow.py from docs/release/SD-38-cyberpunk-red/{workflow-instruction,kanban,epic-breakdown}.md.
// PREFIX = §2.1 verbatim; PROCEDURE = §6 verbatim; CARDS = kanban rows (deps) + §0 (tier, cargo).
// args: { START?: 'E2.5', SKIP?: ['C1'], DONE?: ['C1', ...] }  — DONE/START mark cards already complete on the board.
const PREFIX = __PREFIX__
const PROCEDURE = __PROCEDURE__
const CARDS = __CARDS__

const RESULT = {
  type: 'object',
  properties: {
    status: { type: 'string', enum: ['complete', 'partial', 'blocked-escalated', 'declined'] },
    sha: { type: 'string' }, receipt: { type: 'string' }, summary: { type: 'string' },
    remainder: { type: 'string' }, blocker: { type: 'string' },
    seed_deltas: { type: 'string' },
    discovered_cards: { type: 'array', items: { type: 'object', properties: {
      id: { type: 'string' }, title: { type: 'string' }, tier: { type: 'string' }, cargo: { type: 'boolean' },
      deps: { type: 'array', items: { type: 'string' } }, lane: { type: 'string' }, phase: { type: 'string' } },
      required: ['id', 'title', 'tier', 'cargo', 'deps'] } },
  },
  required: ['status', 'summary'],
}

const PKG = 'docs/release/SD-38-cyberpunk-red'
const MAIN = '/home/ubuntu/workspace/repos/codex/.worktrees/sd38-main'
const prompt = (card, attempt, remainder) => {
  const lane = card.lane
  const tree = lane === 'main' ? MAIN : `/home/ubuntu/workspace/repos/codex/.worktrees/sd38-${lane}`
  const laneNote = lane === 'main'
    ? `You are the serial chain. Your tree is ${MAIN} on branch tranche-18. If it does not exist yet: cd /home/ubuntu/workspace/repos/codex && git fetch origin tranche-18 && git worktree add ${MAIN} tranche-18 (the lead's checkout is NOT on tranche-18). If it exists, it may be STALE: before reading ANY package or repo file run cd ${MAIN} && git fetch origin tranche-18 && test -z "$(git status --porcelain)" && git merge --ff-only origin/tranche-18 && git log --oneline -1; if the status is not empty or the fast-forward fails, return status declined with blocker "sd38-main not clean / not fast-forwardable" and change nothing. Every package file you read (kanban.md, decisions.md, epic-breakdown.md) must be read AFTER this update, from this tree. CARGO_TARGET_DIR=/home/ubuntu/cargo-target/sd38-main.`
    : `You are parallel lane "${lane}". Your tree is ${tree} on branch sd38/${lane}. If the tree exists already (a previous card of this lane made it), reuse it: cd ${tree} && git fetch origin tranche-18 && git rebase origin/tranche-18. Otherwise create it per the prefix (git worktree add -b sd38/${lane} ${tree} origin/tranche-18). CARGO_TARGET_DIR=/home/ubuntu/cargo-target/sd38-${lane}. Land by pushing your commits to tranche-18 per §5 (rebase; never force). If this is the LAST card of your lane (${card.last ? 'it is' : 'it is not'}), remove your worktree and delete your CARGO_TARGET_DIR after the push (git worktree remove ${tree}; git branch -D sd38/${lane}; rm -rf /home/ubuntu/cargo-target/sd38-${lane}).`
  const deps = card.deps.length ? card.deps.join(', ') : '(none)'
  return `${PREFIX}
CARD: ${card.id} — ${card.title}
RETRO_ACTOR=sd38-${card.id.toLowerCase()}   RUN_DESKTOP_AGENT=sd38-${card.id.toLowerCase()}
MODEL TIER: ${card.tier}. Attempt ${attempt} of 3.
${laneNote}

YOUR CARD. Read, in this order, inside your tree: ${PKG}/workflow-instruction.md (all of it; §2.1, §5, §6, §7, §12 bind you), then your card's row in ${PKG}/epic-breakdown.md (criterion, FILES YOU OWN, verification commands, "does not cover") and in ${PKG}/kanban.md, then ${PKG}/decisions.md entries your card names (D-n, A-n, SD-x), then ${PKG}/content-unit-inventory.md figures your card names, then only the repo files your card names. CLAUDE.md/AGENTS.md are already loaded.

DEPENDENCY GATE (R8, you enforce it): before any write, read ${PKG}/kanban.md from origin/tranche-18 (git show origin/tranche-18:${PKG}/kanban.md) and confirm every card in [${deps}] has Status complete. If any is not, return status declined with blocker "deps not complete: <ids>" and do nothing else.
${remainder ? `\nPREVIOUS ATTEMPT WAS PARTIAL. Its remainder, by sub-cause:\n${remainder}\nFinish exactly that remainder; do not redo what landed.\n` : ''}
${PROCEDURE}

RETURN (StructuredOutput): status complete | partial | blocked-escalated | declined; sha (your pushed commit on tranche-18); receipt path; summary (what landed, with every figure's command); remainder (partial only: every remaining item by sub-cause with populations that sum to the stated total); blocker (blocked-escalated/declined only: the exact ruling, scope or mechanism needed); seed_deltas (PF render-hash + SF seed-line result, "unchanged" or the diff); discovered_cards (cards you ADDED to kanban.md with id/title/tier/cargo/deps/lane/phase, else []). Your final text is the StructuredOutput call, nothing else. Never claim complete without the receipt committed and pushed.`
}

// ---- 3-slot cargo semaphore
let slotsFree = 3; const waiters = []
const acquire = () => new Promise(res => { if (slotsFree > 0) { slotsFree--; res() } else waiters.push(res) })
const release = () => { slotsFree++; const w = waiters.shift(); if (w) { slotsFree--; w() } }

// ---- quota gate (decisions §16.3)
let quotaHit = false
const quotaCheck = (r) => { const s = JSON.stringify(r || ''); if (/usage limit|rate limit|quota|limit reached/i.test(s)) quotaHit = true }

// ---- card runner (model on the agent( line; tier must be opus|sonnet|haiku)
const runCard = async (card, attempt = 1, remainder = '') => {
  if (card.tier === 'sonnet + opus') {
    // E7.9: truth-up on sonnet, then the claims critic on opus; both report through the same card.
    const a = await agent(prompt({ ...card, title: card.title + ' — PART 1 truth-up (model sonnet)' }, attempt, remainder), { model: 'sonnet', phase: card.phase, schema: RESULT, label: card.id + '/truth-up' })
    quotaCheck(a); if (!a || a.status !== 'complete') return a || { status: 'declined', summary: 'E7.9 truth-up returned null' }
    const b = await agent(prompt({ ...card, title: card.title + ' — PART 2 claims critic (model opus): refute every capability claim in the refreshed architecture docs against the live code; fix or revert each false claim' }, attempt, remainder), { model: 'opus', phase: card.phase, schema: RESULT, label: card.id + '/claims-critic' })
    quotaCheck(b); return b
  }
  if (!['opus', 'sonnet', 'haiku'].includes(card.tier)) throw new Error(`card ${card.id} has tier "${card.tier}" — refused`)
  const r = await agent(prompt(card, attempt, remainder), { model: card.tier, phase: card.phase, schema: RESULT, label: card.id })
  quotaCheck(r); return r
}

const go = async (card) => {
  let remainder = ''
  for (let attempt = 1; attempt <= 3; attempt++) {
    if (card.cargo) await acquire()
    let r
    try { r = await runCard(card, attempt, remainder) } finally { if (card.cargo) release() }
    if (!r) return { status: 'declined', summary: `${card.id}: agent returned null (skipped or died)` }
    if (r.status === 'complete') return r
    if (r.status === 'partial') { remainder = r.remainder || '(no remainder stated — treat as the whole card)'; log(`${card.id} partial (attempt ${attempt}); remainder: ${remainder.slice(0, 200)}`); continue }
    return r   // blocked-escalated | declined
  }
  return { status: 'partial', summary: `${card.id}: still partial after 3 attempts`, remainder }
}

// ---- dependency-driven scheduler (deps from kanban.md rows; discovered cards join at runtime)
const done = new Set([...(args?.DONE || []), 'C0'])       // C0 = the lead's package commit
const skip = new Set(args?.SKIP || [])
if (args?.START) { const i = CARDS.findIndex(c => c.id === args.START); CARDS.slice(0, i).forEach(c => done.add(c.id)) }
const pending = CARDS.filter(c => !done.has(c.id) && !skip.has(c.id) && c.id !== 'C0')
// mark the last card of each parallel lane so it cleans its tree up
const lastOfLane = {}; for (const c of pending) lastOfLane[c.lane] = c.id
for (const c of pending) c.last = lastOfLane[c.lane] === c.id && c.lane !== 'main'
const results = {}; const inflight = new Map()
let currentPhase = ''
const setPhase = (p) => { if (p !== currentPhase) { currentPhase = p; phase(p) } }
let stop = null
while (pending.length || inflight.size) {
  if (!stop && !quotaHit) {
    for (const c of [...pending]) {
      if (c.deps.every(d => done.has(d))) {
        pending.splice(pending.indexOf(c), 1)
        setPhase(c.phase)
        inflight.set(c.id, go(c).then(r => ({ c, r })))
      }
    }
  }
  if (!inflight.size) break
  const { c, r } = await Promise.race(inflight.values())
  inflight.delete(c.id); results[c.id] = r
  if (r.status === 'complete') {
    done.add(c.id); log(`${c.id} complete ${r.sha || ''}`)
    for (const d of (r.discovered_cards || [])) {
      if (!CARDS.some(x => x.id === d.id)) { const nc = { id: d.id, title: d.title, tier: d.tier, cargo: !!d.cargo, deps: d.deps, lane: d.lane || c.lane, phase: d.phase || c.phase }; CARDS.push(nc); pending.push(nc); log(`discovered card ${d.id} added`) }
    }
  } else {
    stop = { card: c.id, status: r.status, blocker: r.blocker, summary: r.summary, remainder: r.remainder }
    log(`STOP: ${c.id} ${r.status} — ${(r.blocker || r.summary || '').slice(0, 300)}`)
  }
  if (quotaHit && !stop) { stop = { card: c.id, status: 'quota', summary: 'quota stop rule §16.3 — lanes in flight finish; resume with START=' }; log('quota stop rule fired') }
}
const complete = Object.entries(results).filter(([, r]) => r.status === 'complete').map(([id]) => id)
const notComplete = Object.entries(results).filter(([, r]) => r.status !== 'complete').map(([id, r]) => ({ id, status: r.status, blocker: r.blocker, remainder: r.remainder }))
return { stop, complete, notComplete, stillPending: pending.map(c => c.id) }
'''
JS = JS.replace('__PREFIX__', json.dumps(PREFIX)).replace('__PROCEDURE__', json.dumps(PROCEDURE)).replace('__CARDS__', json.dumps(cards, indent=0))
out = PKG / 'artifacts' / 'cycle_0' / 'sd38-workflow.js'
out.write_text(JS)
print(out, len(JS), 'bytes;', len(cards), 'cards;', sum(c['cargo'] for c in cards), 'cargo cards')
print('tiers:', sorted({c['tier'] for c in cards}))
print('lanes:', sorted({c['lane'] for c in cards}))
